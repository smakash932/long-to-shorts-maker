"""
Clip generator using FFmpeg.

Pipeline per clip:
  1. Cut the source video to the clip range with `-ss`/`-to`.
  2. Apply a crop (face-centered single-person, or split-screen for
     multi-speaker).
  3. Apply an anti-copyright filter (subtle but actually noticeable
     pixel-level changes: tiny rotation + color shift + audio re-tune).
  4. Burn the ASS subtitles generated by subtitle_styles.py.
  5. Encode using NVENC when available (GTX 1650), otherwise libx264.
  6. Generate a thumbnail.

Clips are generated in parallel via a thread pool. FFmpeg already uses
all CPU/GPU resources for one encode, so we keep the pool small (2–3 for
NVENC, configurable for CPU) to avoid thrashing.
"""

from __future__ import annotations

import json
import os
import random
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed

from gpu_utils import gpu_info, video_encoder_args
from subtitle_styles import generate_word_by_word_ass
from utils import (
    emit_complete,
    emit_error,
    emit_progress,
    ensure_dirs,
    get_clip_dir,
)


# ---------------------------------------------------------------------------
# Anti-copyright filter
# ---------------------------------------------------------------------------


def _build_anticopy_video_filter(output_w: int, output_h: int, strength: str = "medium") -> str:
    """
    Build an anti-copyright video filter chain.

    Three strength levels:
      - off:    just scale to target resolution (no fingerprint at all)
      - light:  tiny color shift (invisible, fools simple hash matchers)
      - medium: color shift + 1-2px crop pad + tiny rotation (~0.3°)
      - strong: medium + mirror horizontally (visible difference)

    All variants finish by scaling to (output_w, output_h) with lanczos.
    """
    if strength == "off":
        return f"scale={output_w}:{output_h}:flags=lanczos"

    brightness = round(random.uniform(-0.025, 0.025), 4)
    contrast = round(random.uniform(0.97, 1.03), 4)
    saturation = round(random.uniform(0.94, 1.06), 4)
    # Tiny gamma shift further changes pixel histograms without being visible
    gamma = round(random.uniform(0.97, 1.03), 4)

    eq = f"eq=brightness={brightness}:contrast={contrast}:saturation={saturation}:gamma={gamma}"

    if strength == "light":
        return f"scale={output_w}:{output_h}:flags=lanczos,{eq}"

    # medium / strong both apply micro rotation + slight padding crop.
    # Rotation is so small it's invisible but breaks hash-based fingerprinting.
    rot = round(random.uniform(-0.35, 0.35) * 3.14159 / 180, 6)  # ±0.35°
    pad_px = random.randint(2, 6)

    # rotate -> tiny crop (to hide black corners) -> eq -> scale
    chain = (
        f"rotate={rot}:fillcolor=black,"
        f"crop=iw-{pad_px * 2}:ih-{pad_px * 2}:{pad_px}:{pad_px},"
        f"{eq},"
        f"scale={output_w}:{output_h}:flags=lanczos"
    )

    if strength == "strong":
        chain = f"hflip,{chain}"

    return chain


def _build_anticopy_audio_args(strength: str = "medium") -> list[str]:
    """
    Build an FFmpeg audio filter argument list that subtly re-pitches audio.

    Strength levels:
      - off:    no audio filter (re-encode only)
      - light:  ±10–25 cents pitch shift via `asetrate` (sub-perceptible)
      - medium: ±25–40 cents
      - strong: ±40–60 cents
    """
    if strength == "off":
        return []

    cents_ranges = {
        "light": (10, 25),
        "medium": (25, 40),
        "strong": (40, 60),
    }
    low, high = cents_ranges.get(strength, cents_ranges["medium"])
    cents = random.randint(low, high) * random.choice([-1, 1])
    ratio = 2 ** (cents / 1200)  # pitch ratio for `cents` cents

    # asetrate changes both pitch + speed; atempo undoes the speed change.
    # We must split atempo across multiple stages if ratio is outside [0.5, 2].
    # For ±60 cents, ratio is well within [0.5, 2], so a single atempo works.
    sample_rate = 48000
    new_rate = int(sample_rate * ratio)
    af = f"asetrate={new_rate},aresample={sample_rate},atempo={1/ratio:.6f}"

    return ["-af", af]


# ---------------------------------------------------------------------------
# Subtitle path escaping for FFmpeg's ass= filter
# ---------------------------------------------------------------------------


def _safe_ass_path(sub_path: str) -> str:
    """
    Convert a path to FFmpeg `ass=` filter safe format.

    On Windows, drive-letter colons confuse FFmpeg's filter parser, so we
    prefer a relative path from cwd. Spaces and remaining colons are
    backslash-escaped.
    """
    try:
        cwd = os.getcwd()
        rel_path = os.path.relpath(sub_path, cwd)
        safe = rel_path.replace('\\', '/')
    except ValueError:
        # Different drive — fall back to absolute path
        safe = sub_path.replace('\\', '/')

    safe = safe.replace(':', '\\:')
    safe = safe.replace(' ', '\\ ')
    return safe


